import { readFile, writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import { format } from "prettier";

const P3_EVENT_NAMES = [
  "KeeperHistoryStarted",
  "RevealTimestamped",
  "BucketListed",
  "SellHistoryUpdated",
];
const M2_EVENT_NAMES = [
  "ExecBegun",
  "ExecEnded",
  "SoldBack",
  "CardFedBack",
  "OwedWithdrawn",
  "BinderClosed",
];
const M4_EVENT_NAMES = [
  "PoweredOn",
  "OnePctLive",
  "OnePctPulled",
  "JackpotWon",
  "CreatorFeesCollected",
  "FinalPullStarted",
  "FinalSolClaimed",
  "FinalTokensClaimed",
  "LaunchFeesClaimed",
];

/** Keep only the final program event ABI and its transitive field definitions. */
export function eventIdl(idl) {
  if (new Set(idl.types.map(({ name }) => name)).size !== idl.types.length)
    throw new Error("Duplicate event type definitions");
  if (new Set(idl.events.map(({ name }) => name)).size !== idl.events.length)
    throw new Error("Duplicate event names");
  if (
    new Set(idl.events.map(({ discriminator }) => discriminator.join(",")))
      .size !== idl.events.length
  )
    throw new Error("Duplicate event discriminators");
  const definitions = new Map(idl.types.map((type) => [type.name, type]));
  const referenced = new Set();
  function visit(value) {
    if (!value || typeof value !== "object") return;
    if (value.defined) include(value.defined.name);
    for (const child of Object.values(value)) visit(child);
  }
  function include(name) {
    if (referenced.has(name)) return;
    const definition = definitions.get(name);
    if (!definition) throw new Error(`Missing event type: ${name}`);
    referenced.add(name);
    visit(definition.type);
  }
  idl.events.forEach(({ name }) => include(name));
  return {
    address: idl.address,
    metadata: idl.metadata,
    instructions: [],
    events: idl.events,
    types: idl.types.filter(({ name }) => referenced.has(name)),
  };
}

function fieldType(type) {
  if (typeof type !== "string") {
    if (type.defined) return type.defined.name;
    if (type.array)
      return `readonly [${Array.from({ length: type.array[1] }, () => fieldType(type.array[0])).join(", ")}]`;
  }
  const primitive = {
    pubkey: "string",
    u8: "number",
    u16: "number",
    u32: "number",
    u64: "bigint",
    i64: "bigint",
    bool: "boolean",
  }[type];
  if (!primitive)
    throw new Error(`Unsupported event type: ${JSON.stringify(type)}`);
  return primitive;
}

export async function eventTypes(idls) {
  const { types: definitions, events } = eventIdl({
    ...idls[0],
    events: idls.flatMap((idl) => idl.events),
    types: idls.flatMap((idl) => idl.types),
  });
  const structures = definitions.map(({ name, type }) => {
    if (type.kind !== "struct")
      throw new Error(`Unsupported event structure: ${name}`);
    return `export interface ${name} {\n${type.fields.map((field) => `${field.name}: ${fieldType(field.type)};`).join("\n")}\n}`;
  });
  return format(
    `// Generated by scripts/copy-idl.mjs from the final program IDL.\n${structures.join("\n\n")}\n\nexport interface OnepercentEventMap {\n${events.map(({ name }) => `${name}: ${name};`).join("\n")}\n}\nexport type OnepercentEventName = keyof OnepercentEventMap;\nexport type OnepercentEvent = {\n[N in OnepercentEventName]: { name: N; data: OnepercentEventMap[N] };\n}[OnepercentEventName];\n`,
    { parser: "typescript" },
  );
}

export async function writeEventIdl(idl, appDirectory) {
  const directory = new URL("packages/sdk/src/events/", appDirectory);
  const final = eventIdl(idl);
  const previous = JSON.parse(
    await readFile(new URL("m2-provisional.json", directory), "utf8"),
  );
  eventIdl(previous);
  if (
    !isDeepStrictEqual(
      previous.events.map(({ name }) => name).sort(),
      [...M2_EVENT_NAMES].sort(),
    )
  )
    throw new Error("M2 snapshot must contain exactly the six issued events");
  // The S1 snapshot is a compatibility check, never an overlay on the final ABI.
  for (const field of ["events", "types"]) {
    for (const definition of previous[field]) {
      const generated = final[field].find(
        ({ name }) => name === definition.name,
      );
      if (!isDeepStrictEqual(generated, definition))
        throw new Error(
          `Final IDL differs from the S1 event ABI: ${definition.name}`,
        );
    }
  }
  const m1 = eventIdl({
    ...final,
    events: final.events.filter(
      ({ name }) =>
        !M2_EVENT_NAMES.includes(name) &&
        !M4_EVENT_NAMES.includes(name) &&
        !P3_EVENT_NAMES.includes(name),
    ),
  });
  const m1Types = new Set(m1.types.map(({ name }) => name));
  const m2 = {
    events: M2_EVENT_NAMES.map((name) =>
      final.events.find((event) => event.name === name),
    ),
    types: previous.types
      .map(({ name }) => final.types.find((type) => type.name === name))
      .filter(({ name }) => !m1Types.has(name)),
  };
  const m4 = eventIdl({
    ...final,
    events: final.events.filter(({ name }) => M4_EVENT_NAMES.includes(name)),
  });
  const p3 = eventIdl({
    ...final,
    events: final.events.filter(({ name }) => P3_EVENT_NAMES.includes(name)),
  });
  const types = await eventTypes([m1, m2, m4, p3]);
  await writeFile(
    new URL("p3.json", directory),
    await format(JSON.stringify(p3), { parser: "json" }),
  );
  await writeFile(
    new URL("m1.json", directory),
    await format(JSON.stringify(m1), { parser: "json" }),
  );
  await writeFile(
    new URL("m2-provisional.json", directory),
    await format(JSON.stringify(m2), { parser: "json" }),
  );
  await writeFile(new URL("types.ts", directory), types);
  await writeFile(
    new URL("m4.json", directory),
    await format(JSON.stringify(m4), { parser: "json" }),
  );
}
